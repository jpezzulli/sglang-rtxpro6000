#!/usr/bin/env python3
"""CPU-only guards for the accepted FlashInfer packaging manifest.

Runs with any Python 3.11+ from the repository root, no interpreter
environment needed:

    python3 -m unittest scripts.pennyroyal.flashinfer.test_accepted_sources

and equally under pytest. It checks identities the manifest owes to this
checkout; the digest values themselves are regenerated by
``install.py --record`` from a fresh extraction of the pinned wheel.
"""

import json
import re
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[2]
MANIFEST = json.loads((HERE / "accepted-sources.json").read_text())
PYPROJECT = (REPO_ROOT / "python" / "pyproject.toml").read_text()
DOCKERFILE = (REPO_ROOT / "docker" / "Dockerfile").read_text()
HEX64 = re.compile(r"\A[0-9a-f]{64}\Z")


def pyproject_flashinfer_pin() -> str:
    m = re.search(r'"flashinfer_python\[[^\]]*\]==([0-9][^"]*)"', PYPROJECT)
    assert m, "python/pyproject.toml no longer pins flashinfer_python"
    return m.group(1)


class TestAcceptedSources(unittest.TestCase):
    def test_manifest_names_the_pinned_flashinfer(self):
        pin = pyproject_flashinfer_pin()
        self.assertEqual(MANIFEST["flashinfer_python"], pin)
        self.assertEqual(
            MANIFEST["flashinfer_wheel"],
            f"flashinfer_python-{pin}-py3-none-any.whl",
        )
        self.assertRegex(MANIFEST["flashinfer_wheel_sha256"], HEX64)

    def test_jit_cache_matches_the_pinned_family_and_the_dockerfile(self):
        pin = MANIFEST["flashinfer_python"]
        self.assertEqual(MANIFEST["flashinfer_jit_cache"], f"{pin}+cu130")
        docker_pin = re.search(r"ARG FLASHINFER_VERSION=(\S+)", DOCKERFILE).group(1)
        self.assertEqual(pin, docker_pin)

    def test_every_mailbox_is_carried_with_attribution(self):
        self.assertTrue(MANIFEST["patches"], "no accepted sources remain")
        for entry in MANIFEST["patches"]:
            patch = (HERE / entry["patch"]).resolve()
            self.assertTrue(patch.is_file(), entry["patch"])
            text = patch.read_text()
            self.assertTrue(text.startswith("From "), f"{entry['patch']} is not a mailbox")
            self.assertRegex(entry["author"], r"\S+ <\S+@\S+>")
            self.assertTrue(entry["attribution"].strip())
            self.assertTrue(entry["commits"], f"{entry['patch']} lost its commit ids")
            for spec in entry["files"]:
                self.assertTrue(spec["path"].strip("/") and ".." not in Path(spec["path"]).parts)
                self.assertRegex(spec["stock_sha256"], HEX64, spec["path"])
                self.assertRegex(spec["accepted_sha256"], HEX64, spec["path"])
                self.assertNotEqual(
                    spec["stock_sha256"],
                    spec["accepted_sha256"],
                    f"{spec['path']} is accepted unchanged; drop the entry or the patch",
                )


if __name__ == "__main__":
    unittest.main()
